export function generateRandomName(): string {
  const prefix = PREFIX_MODIFIERS[Math.floor(Math.random() * PREFIX_MODIFIERS.length)];
  const name = ALLOWED_NAMES[Math.floor(Math.random() * ALLOWED_NAMES.length)];
  return `${prefix} ${name}`;
}
